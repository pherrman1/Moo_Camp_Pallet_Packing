#!/usr/bin/env python3
"""
mcpp_generator.py
=================

Realistic benchmark instance generator for the Mixed-Case Palletization Problem
(MCPP) / 3D Bin Packing Problem (3DBPP).

The core generator is a reimplementation of the instance generator described in

    S. Elhedhli, F. Gzara, B. Yildiz (2019).
    "Three-Dimensional Bin Packing and Mixed-Case Palletization."
    INFORMS Journal on Optimization 1(4), 323-352.   Section 7.1, Tables 2-4.

Their generator was trained on 166,406 industrial items (73,978 distinct) and
replaces the classical Martello et al. (2000) random instances, which are
unrealistic: ~4.31 items per bin versus >=90 items per bin in real data.

Model (paper, Section 7.1)
--------------------------
An item is *not* generated by drawing three independent side lengths. Instead
the paper draws shape ratios and a volume, which keeps the dimensions properly
related to each other:

    depth / width   ~ Normal(0.695, 0.118)
    height / width  ~ Lognormal(-0.654, 0.453)
    repetition      ~ Lognormal(0.544, 0.658)      (copies of the same SKU)
    volume          ~ one of 5 k-means categories, mixed per instance class

    v = w * d * h = w * (p*w) * (q*w) = p*q*w^3   =>   w = (v/(p*q))^(1/3)

Volume categories (dm^3), from k-means with k = 5 on the industry data:
    1: [ 2.72,  12.04]   72,037 items
    2: [12.05,  20.23]   55,436 items
    3: [20.28,  32.42]   26,254 items
    4: [32.44,  54.08]    9,304 items
    5: [54.31, 100.21]    3,376 items

Four instance classes were obtained by clustering real orders by their category
mix (paper Table 3). Class 1 = medium boxes, Class 4 = many small boxes.

Verification of the reimplementation
------------------------------------
Paper Table 4 reports the centroid (w, d, h, v) of the *generated* data as

    class 1: (338.80, 232.81, 181.95, 13.72)
    class 2: (336.89, 231.18, 180.51, 13.53)
    class 3: (312.77, 215.31, 168.00, 10.97)
    class 4: (304.86, 209.66, 164.87, 10.19)

Running `python mcpp_generator.py validate` reproduces classes 1, 3 and 4 to
within ~2 % on every dimension, which confirms the reconstruction of the
(unpublished) generator code. Class 2 comes out heavier (mean volume ~19.8 dm^3
instead of 13.53) because it is the only class with a substantial share of the
two largest volume categories (7.94 % + 3.28 %). The paper's own numbers are
suspicious here: its *industry* class-2 centroid volume is 19.54 dm^3, i.e. very
close to what this generator produces, while the reported *generated* value of
13.53 is almost identical to class 1. Two explanations are consistent with the
text: Table 4 may report a k-means centroid (pulled towards the dense small-box
cluster) rather than an arithmetic mean, or volumes may be drawn from a
decreasing density inside each category rather than uniformly. Uniform sampling
inside the category interval is used here because it is the only choice the
paper's description supports.

Extensions for the retail pallet-loading task
---------------------------------------------
The paper only generates geometry. Everything below is an *extension* and is
clearly marked as such in the code and in the output metadata ("extended": true):

  * weight, derived from a product-family-specific density,
  * product family and a food/chemical flag (for the vertical-ordering rule
    "food above cleaning agents"),
  * load-bearing capacity (kPa) and a fragile flag,
  * an orientation flag (`upright_only`, e.g. liquids) restricting rotations,
  * a store zone and a retrieval priority (picking sequence).

These follow common practice in the container-loading literature (e.g. the
load-bearing convention sigma_i ~ U[0, 3*h_i] of Junqueira et al. 2012) but are
*not* fitted to the industry data of Elhedhli et al.

Usage
-----
  # one instance, human-readable summary + JSON
  python mcpp_generator.py single --class 2 --items 1000 --seed 7 -o out/

  # D-Wave 3D-bin-packing input plus rich metadata JSON
  python mcpp_generator.py single --class 4 --items 20 --seed 7 \
      --formats solver,json --solver-bins 2 -o input/generated/

  # the full 4 classes x {50..2000} x 5 replications benchmark set (160 files)
  python mcpp_generator.py batch -o benchmark/

  # reproduce Table 4 of the paper
  python mcpp_generator.py validate

  # a tiny didactic instance for a first MIP model
  python mcpp_generator.py single --class 4 --items 12 --seed 1 --no-extended

Only the Python standard library is required.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import os
import random
import statistics
