def _add_common(sp: argparse.ArgumentParser) -> None:
    sp.add_argument("-o", "--outdir", default="instances", help="output directory")
    sp.add_argument("--pallet", choices=sorted(PALLETS), default="euro-180",
                    help="loading space (default: Euro pallet, 1800 mm height)")
    sp.add_argument("--formats", default="json,csv",
                    help="comma separated subset of json,csv,txt,solver")
    sp.add_argument("--solver-bins", type=int, default=None,
                    help="maximum bins in solver output (default: volume lower bound)")
    sp.add_argument("--no-extended", action="store_true",
                    help="geometry only, exactly as in the paper")


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="Realistic MCPP / 3DBPP instance generator "
                    "(Elhedhli, Gzara & Yildiz 2019).")
    sub = ap.add_subparsers(dest="cmd", required=True)

    s1 = sub.add_parser("single", help="generate one instance")
    s1.add_argument("--class", dest="cls", type=int, default=1, choices=[1, 2, 3, 4])
    s1.add_argument("--items", type=int, default=1000)
    s1.add_argument("--seed", type=int, default=0)
    _add_common(s1)

    s2 = sub.add_parser("batch", help="generate a full benchmark set")
    s2.add_argument("--classes", default="1,2,3,4")
    s2.add_argument("--sizes", default=",".join(str(s) for s in PAPER_SIZES))
    s2.add_argument("--replications", type=int, default=5)
    s2.add_argument("--seed0", type=int, default=0)
    _add_common(s2)

    s3 = sub.add_parser("validate", help="reproduce Table 4 of the paper")
    s3.add_argument("--items", type=int, default=2000)
    s3.add_argument("--replications", type=int, default=20)

    args = ap.parse_args(argv)

    if args.cmd == "validate":
        print(validate_against_paper(args.items, args.replications))
        return 0

    pallet = PALLETS[args.pallet]
    formats = [f.strip() for f in args.formats.split(",") if f.strip()]
    unsupported_formats = set(formats) - {"json", "csv", "txt", "solver"}
    if unsupported_formats:
        ap.error(f"unsupported formats: {', '.join(sorted(unsupported_formats))}")
    extended = not args.no_extended

    if args.cmd == "single":
        inst = generate_instance(args.items, args.cls, args.seed, pallet, extended)
        print(summary_text(inst))
        for p in write_instance(inst, args.outdir, formats, args.solver_bins):
            print("  wrote", p)
        return 0

    # batch
    classes = [int(c) for c in args.classes.split(",")]
    sizes = [int(s) for s in args.sizes.split(",")]
    index = []
    count = 0
    for cls in classes:
        for n in sizes:
            for r in range(1, args.replications + 1):
                seed = args.seed0 + 100000 * cls + 100 * r + n
                name = f"mcpp_c{cls}_n{n:04d}_i{r}"
                inst = generate_instance(n, cls, seed, pallet, extended, name)
                write_instance(inst, args.outdir, formats, args.solver_bins)
                index.append({"name": name, "class": cls, "items": n,
                              "replication": r, "seed": seed, **inst.stats})
                count += 1
    idx_path = os.path.join(args.outdir, "index.csv")
    with open(idx_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(index[0].keys()))
        writer.writeheader()
        for row in index:
            writer.writerow(row)
    print(f"generated {count} instances in {args.outdir}")
    print("index:", idx_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
